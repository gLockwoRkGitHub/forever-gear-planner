"""Build the in-game addon: addon/ForeverSuite + data/items.js + data/mechanics.json -> build/addon/ForeverSuite
and build/ForeverSuite.zip (ready to unpack into World of Warcraft/_forever_/Interface/AddOns).

The addon carries the whole item database, so it ranks gear in the game for the live level and gear.
The version is addon/VERSION plus the date of the item data, e.g. 1.0.0-20261110.

Usage: python scripts/build_addon.py
"""
import json
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "addon" / "ForeverSuite"
OUT_DIR = ROOT / "build" / "addon"
ADDON = OUT_DIR / "ForeverSuite"
ZIP = ROOT / "build" / "ForeverSuite.zip"

# fields of an item the addon uses (notes are left out: the game's own tooltip shows them)
ITEM_KEYS = ["id", "n", "q", "il", "rq", "g", "sl", "ty", "st", "src", "ic", "dmgMin", "dmgMax", "speed", "dps",
             "bop", "boe", "rnd", "np", "cl"]
SRC_KEYS = ["t", "n", "id", "w", "lv", "dc", "ml", "ql", "rc", "dq", "sk", "g"]
CHUNK = 300  # items per generated function (keeps every function well below Lua's constant limit)


def lua(v):
    """A Python value as a Lua literal."""
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 6)).rstrip("0").rstrip(".") if v != int(v) else str(int(v))
    if isinstance(v, str):
        s = v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
        return '"' + s + '"'
    if isinstance(v, list):
        return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            if x is None:
                continue
            key = k if k.isidentifier() else "[" + lua(k) + "]"
            parts.append(key + "=" + lua(x))
        return "{" + ",".join(parts) + "}"
    raise TypeError(type(v))


def load_items():
    text = (ROOT / "data" / "items.js").read_text(encoding="utf-8")
    return json.loads(text[text.index("{"):text.rindex("}") + 1])


def item_lua(it):
    out = {}
    for k in ITEM_KEYS:
        if k not in it or it[k] is None:
            continue
        if k == "src":
            out[k] = [{sk: s[sk] for sk in SRC_KEYS if s.get(sk) is not None} for s in it[k]]
        else:
            out[k] = it[k]
    return lua(out)


def write_data(data, mech, meta, version):
    items = data["items"]
    lines = ["-- Generated by scripts/build_addon.py from data/items.js. Do not edit.",
             "local _, FS = ...", "local D = FS.Data", "local I = D.items"]
    for start in range(0, len(items), CHUNK):
        lines.append("local function chunk%d()" % (start // CHUNK + 1))
        for it in items[start:start + CHUNK]:
            lines.append("I[#I+1]=" + item_lua(it))
        lines.append("end")
        lines.append("chunk%d()" % (start // CHUNK + 1))
    (ADDON / "Data" / "Items.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")

    bosses = {name: [b["n"] for b in lst if b.get("n")] for name, lst in (data.get("bosses") or {}).items()}
    info = {"version": version, "generated": data.get("generated"), "build": data.get("build"), "count": len(items),
            "questie": meta.get("questieDelta")}
    other = ["-- Generated by scripts/build_addon.py. Do not edit.", "local _, FS = ...", "local D = FS.Data",
             "D.meta = " + lua(info), "D.mech = " + lua(mech), "D.bosses = " + lua(bosses)]
    (ADDON / "Data" / "Meta.lua").write_text("\n".join(other) + "\n", encoding="utf-8")

    # quests open to Tauren Shaman and Druid (data/quests.json, from the weekly item update): Q[id] = {name, zone, level, min level}
    qpath = ROOT / "data" / "quests.json"
    quests = json.loads(qpath.read_text(encoding="utf-8")) if qpath.exists() else {"zones": [], "quests": {}}
    qlines = ["-- Generated by scripts/build_addon.py from data/quests.json. Do not edit.", "local _, FS = ...",
              "local D = FS.Data", "D.questZones = " + lua(quests["zones"]), "local Q = {}", "D.quests = Q"]
    entries = sorted(quests["quests"].items(), key=lambda kv: int(kv[0]))
    for start in range(0, len(entries), 500):
        qlines.append("local function chunk%d()" % (start // 500 + 1))
        for qid, (name, zone, level, minlevel) in entries[start:start + 500]:
            qlines.append("Q[%d]={%s,%d,%d,%d}" % (int(qid), lua(name), zone + 1, level, minlevel))
        qlines.append("end")
        qlines.append("chunk%d()" % (start // 500 + 1))
    (ADDON / "Data" / "Quests.lua").write_text("\n".join(qlines) + "\n", encoding="utf-8")
    return len(entries)


def main():
    data = load_items()
    mech = json.loads((ROOT / "data" / "mechanics.json").read_text(encoding="utf-8"))
    meta_path = ROOT / "data" / "items-meta.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}
    base = (ROOT / "addon" / "VERSION").read_text(encoding="utf-8").strip()
    version = base + "-" + (data.get("generated") or "dev").replace("-", "")

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    shutil.copytree(SRC, ADDON)
    (ADDON / "Data").mkdir(exist_ok=True)
    toc = ADDON / "ForeverSuite.toc"
    toc.write_text(toc.read_text(encoding="utf-8").replace("@VERSION@", version), encoding="utf-8")
    nquests = write_data(data, mech, meta, version)

    ZIP.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(ADDON.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT_DIR).as_posix())
    (ROOT / "build" / "addon-version.txt").write_text(version + "\n", encoding="utf-8")
    print(f"addon {version}: {len(data['items'])} items, {nquests} quests -> {ZIP} ({ZIP.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
